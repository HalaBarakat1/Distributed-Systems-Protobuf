package org.ds.library.grpc;

import io.grpc.Server;
import io.grpc.ServerBuilder;
import io.grpc.Status;
import io.grpc.stub.StreamObserver;
import org.ds.library.SampleData;
import org.ds.library.proto.Book;
import org.ds.library.proto.CreateBookResponse;
import org.ds.library.proto.GetBookRequest;
import org.ds.library.proto.Genre;
import org.ds.library.proto.LibraryServiceGrpc;
import org.ds.library.proto.ListBooksRequest;

import java.io.IOException;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/** gRPC server: implements the LibraryService defined in library.proto. */
public class LibraryServer {

    public static final int PORT = 50051;

    public static void main(String[] args) throws IOException, InterruptedException {
        Server server = ServerBuilder.forPort(PORT)
                .addService(new LibraryServiceImpl())
                .build()
                .start();
        System.out.println("[server] LibraryService listening on port " + PORT);
        Runtime.getRuntime().addShutdownHook(new Thread(() -> {
            System.out.println("[server] shutting down");
            server.shutdown();
        }));
        server.awaitTermination();
    }

    /** Extends the base class generated by protoc-gen-grpc-java. */
    static class LibraryServiceImpl extends LibraryServiceGrpc.LibraryServiceImplBase {

        // in-memory storage: ISBN -> Book (thread safe because gRPC serves calls on several threads)
        private final Map<String, Book> books = new ConcurrentHashMap<>();

        LibraryServiceImpl() {
            for (Book b : SampleData.library().getBooksList()) {
                books.put(b.getIsbn(), b);
            }
        }

        @Override
        public void getBook(GetBookRequest request, StreamObserver<Book> responseObserver) {
            System.out.println("[server] GetBook isbn=" + request.getIsbn());
            Book book = books.get(request.getIsbn());
            if (book == null) {
                responseObserver.onError(Status.NOT_FOUND
                        .withDescription("No book with ISBN " + request.getIsbn())
                        .asRuntimeException());
                return;
            }
            responseObserver.onNext(book);
            responseObserver.onCompleted();
        }

        @Override
        public void createBook(Book request, StreamObserver<CreateBookResponse> responseObserver) {
            System.out.println("[server] CreateBook title=\"" + request.getTitle() + "\" isbn=" + request.getIsbn());
            if (request.getIsbn().isBlank() || request.getTitle().isBlank()) {
                responseObserver.onError(Status.INVALID_ARGUMENT
                        .withDescription("title and isbn are required").asRuntimeException());
                return;
            }
            Book previous = books.putIfAbsent(request.getIsbn(), request);
            if (previous != null) {
                responseObserver.onError(Status.ALREADY_EXISTS
                        .withDescription("ISBN " + request.getIsbn() + " already exists").asRuntimeException());
                return;
            }
            responseObserver.onNext(CreateBookResponse.newBuilder()
                    .setCreated(true)
                    .setMessage("Book \"" + request.getTitle() + "\" added")
                    .setTotalBooks(books.size())
                    .build());
            responseObserver.onCompleted();
        }

        @Override
        public void listBooks(ListBooksRequest request, StreamObserver<Book> responseObserver) {
            System.out.println("[server] ListBooks genre=" + request.getGenre());
            books.values().stream()
                    .filter(b -> request.getGenre() == Genre.GENRE_UNSPECIFIED || b.getGenre() == request.getGenre())
                    .sorted((a, b) -> a.getTitle().compareTo(b.getTitle()))
                    .forEach(responseObserver::onNext);   // each Book is a separate message on the same stream
            responseObserver.onCompleted();
        }
    }
}
